import pandas as pd
import json
import matplotlib.pyplot as plt
from matplotlib.ticker import MultipleLocator
import os
from pptx import Presentation
from pptx.util import Inches, Pt
import math
import traceback

def draw_reject_map(fig_name, active_dies, reject_dies, title):
    fig, ax = plt.subplots(figsize=(3, 3))
    xs, ys = [], []
    for x, y in active_dies:
        xs.append(x)
        ys.append(y)
    
    # Draw all active dies in light grey, smaller scale for the 3x3 plot so they don't overlap
    ax.scatter(xs, ys, color='#E0E0E0', marker='s', s=40, edgecolor='white', alpha=0.5)
    
    r_xs, r_ys = [], []
    for (x, y), fb_val in reject_dies.items():
        r_xs.append(x)
        r_ys.append(y)
        # Font size adjusted for the small 3x3 layout to prevent overlap
        ax.text(x, y, str(int(fb_val)), ha='center', va='center', fontsize=4.5, color='black', zorder=3, weight='bold')
        
    if r_xs:
        # Highlight failed dies in bright red, matched to the specific cell size
        ax.scatter(r_xs, r_ys, color='#FF6666', marker='s', s=40, edgecolor='white', zorder=2, alpha=0.9)
        
    ax.set_aspect('equal')
    ax.set_title(title, fontsize=10, weight='bold')
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.spines['bottom'].set_color('#888888')
    ax.spines['left'].set_color('#888888')
    ax.tick_params(axis='both', colors='#888888', labelsize=6)
    ax.xaxis.set_major_locator(MultipleLocator(1))
    ax.yaxis.set_major_locator(MultipleLocator(1))
    ax.set_xlabel('X Coordinate', fontsize=7, color='#555555', weight='bold')
    ax.set_ylabel('Y Coordinate', fontsize=7, color='#555555', weight='bold')
    plt.tight_layout()
    plt.savefig(fig_name, dpi=120)
    plt.close()

def _add_df_table(slide, df, left, top, width, height, font_size=Pt(9)):
    rows, cols = df.shape
    if rows == 0 or cols == 0: return
    try:
        table_shape = slide.shapes.add_table(rows+1, cols, left, top, width, height)
        table = table_shape.table
        
        for c, col_name in enumerate(df.columns):
            cell = table.cell(0, c)
            cell.text = str(col_name)
            for p in cell.text_frame.paragraphs:
                p.font.size = font_size
                p.font.bold = True
                
        for r in range(rows):
            for c in range(cols):
                val = df.iloc[r, c]
                cell = table.cell(r+1, c)
                val_text = str(int(val)) if pd.notnull(val) and isinstance(val, (int, float)) and int(val) == val else str(val) if pd.notnull(val) else ''
                cell.text = val_text
                for p in cell.text_frame.paragraphs:
                    p.font.size = font_size
    except Exception as e:
        print(f"Table error: {e}")

def generate_reject_ppt(die_csv, map_json, output_ppt):
    print("Generating Reject Bin Summary PPT...")
    
    try:
        prs = Presentation()
        prs.slide_width = Inches(13.3333333)
        prs.slide_height = Inches(7.5)
    except Exception as e:
        print("Error initializing Presentation:", e)
        return
    
    import datetime
    today_str = datetime.date.today().strftime('%m/%d/%Y')
    
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    slide.shapes.title.text = 'SDHMT Reject Bin Summary'
    try:
        slide.placeholders[1].text = f'generated by pocketflow on {today_str}\npocketflow app author: Yang1.Xiang'
    except:
        pass
    
    df = pd.read_csv(die_csv)
    df = df.dropna(subset=['SORT_X', 'SORT_Y', 'INTERFACE_BIN', 'FUNCTIONAL_BIN'])
    
    maps = json.load(open(map_json, encoding='utf-8'))
    
    df['INTERFACE_BIN'] = df['INTERFACE_BIN'].astype(int)
    df['FUNCTIONAL_BIN'] = df['FUNCTIONAL_BIN'].astype(int)
    
    # Filters
    # Remove IB 1 (Passes)
    df = df[df['INTERFACE_BIN'] != 1]
    # Remove IB 6 (Skipped)
    df = df[df['INTERFACE_BIN'] != 6]
    # Keep only 93 where FB != 9301
    df = df[~((df['INTERFACE_BIN'] == 93) & (df['FUNCTIONAL_BIN'] == 9301))]
    
    fail_ibs = sorted(df['INTERFACE_BIN'].unique())
    
    for ib in fail_ibs:
        ib_df = df[df['INTERFACE_BIN'] == ib]
        if ib_df.empty: continue
        
        # Pivot table to count distinct FBs per lot and wafer
        index_cols = ['LOT', 'WAFER_SCRIBE']
        if 'DEVREVSTEP' in df.columns: index_cols.append('DEVREVSTEP')
        
        pivot = pd.pivot_table(ib_df, index=index_cols, columns='FUNCTIONAL_BIN', values='INTERFACE_BIN', aggfunc='count', fill_value=0)
        
        pivot[f'IB{ib} count'] = pivot.sum(axis=1)
        
        fb_cols = [c for c in pivot.columns if c != f'IB{ib} count']
        # Only keep FBs that have actual counts for this IB
        fb_cols = [c for c in fb_cols if pivot[c].sum() > 0]
        
        rename_dict = {c: f'FB{c} count' for c in fb_cols}
        pivot = pivot.rename(columns=rename_dict)
        
        cols = [f'IB{ib} count'] + [rename_dict[c] for c in fb_cols]
        pivot = pivot[cols].reset_index()
        
        wafers_list = pivot[index_cols].to_dict('records')
        
        # Pagination: 4 wafers max per slide (so maps fit neatly on the bottom)
        batch_size = 4
        num_batches = math.ceil(len(wafers_list) / batch_size)
        
        for batch_idx in range(num_batches):
            start_idx = batch_idx * batch_size
            end_idx = start_idx + batch_size
            
            batch_wafers = wafers_list[start_idx:end_idx]
            batch_pivot = pivot.iloc[start_idx:end_idx]
            
            slide = prs.slides.add_slide(prs.slide_layouts[5]) # Title only layout
            try:
                title_shape = slide.shapes.title
                title_shape.text = f'IB{ib} Fail Summary' + (f' ({batch_idx+1}/{num_batches})' if num_batches > 1 else '')
            except: pass
            
            # Dynamic height depending on rows
            table_height = Inches(0.5 + 0.3 * len(batch_pivot))
            _add_df_table(slide, batch_pivot, left=Inches(0.5), top=Inches(1.2), width=Inches(12.0), height=table_height)

            # Maps row placement
            map_y = Inches(1.2) + table_height + Inches(0.4)
            map_width = Inches(2.9) # Fit 4 across 13.3 inch width

            for i, w_info in enumerate(batch_wafers):
                lot = w_info['LOT']
                wafer = w_info['WAFER_SCRIBE']
                devrevstep = str(w_info.get('DEVREVSTEP', '8FST'))
                
                active_dies = maps.get(devrevstep, maps.get('8FST', {})).get('active_dies', [])

                # Fetch raw specific dies for that particular failure
                w_df = ib_df[(ib_df['LOT'] == lot) & (ib_df['WAFER_SCRIBE'] == wafer)]
                reject_dict = {(int(row['SORT_X']), int(row['SORT_Y'])): row['FUNCTIONAL_BIN'] for _, row in w_df.iterrows()}

                fig_name = f'temp_reject_{ib}_{lot}_{w_info["WAFER_SCRIBE"]}_{i}.png'
                draw_reject_map(fig_name, active_dies, reject_dict, f'{lot}\nWafer {wafer} ({devrevstep})')

                map_x = Inches(0.5 + i * 3.1)
                slide.shapes.add_picture(fig_name, map_x, map_y, width=map_width)
                os.remove(fig_name)

                # Add text box for coordinates
                txbox = slide.shapes.add_textbox(map_x, map_y + map_width, map_width, Inches(1.0))
                tf = txbox.text_frame
                tf.word_wrap = True
                tf.text = "Failed Dies (X, Y):\n" + ", ".join([f"({x},{y})" for x, y in reject_dict.keys()])
                for paragraph in tf.paragraphs:
                    for run in paragraph.runs:
                        run.font.size = Pt(9)
    try:
        prs.save(output_ppt)
        print(f'Successfully generated {output_ppt}')
    except Exception as e:
        print(f'Runtime exception saving presentation: {e}')
        traceback.print_exc()

if __name__ == '__main__':
    generate_reject_ppt('SDHMT die level data.csv', 'domain-knowledge/wafer-map/all_product_maps.json', 'SDHMT reject bin summary.pptx')
